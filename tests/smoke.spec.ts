import { expect, test } from '@playwright/test'

test('builds a directed weighted graph and opens its snapshot in a fresh browser', async ({ page, browser, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await expect(page).toHaveTitle(/GraphLab/)
  await page.getByRole('button', { name: 'Clear graph' }).click()
  const canvas = page.getByRole('group', { name: 'Interactive graph canvas' })
  await canvas.click({ position: { x: 200, y: 140 } })
  await canvas.click({ position: { x: 340, y: 225 } })
  await page.getByRole('switch', { name: 'Directed graph' }).click()
  await page.getByRole('switch', { name: 'Weighted graph' }).click()
  await page.getByRole('button', { name: 'Connect' }).click()
  await canvas.getByRole('button', { name: 'Node A' }).click()
  await canvas.getByRole('button', { name: 'Node B' }).click()
  const weight = page.getByRole('textbox', { name: 'Weight A to B' })
  await weight.fill('2.5')
  await weight.press('Enter')
  await page.getByRole('textbox', { name: 'Graph title' }).fill('Shared example')
  await page.getByRole('button', { name: 'Save & Share' }).click()
  const link = page.getByRole('textbox', { name: 'Share URL' })
  await expect(link).toHaveValue(/\/graph\/[a-f0-9-]+$/)
  const savedUrl = await link.inputValue()
  const clipboard = await page.evaluate(() => navigator.clipboard.readText())
  expect(clipboard).toBe(savedUrl)
  const fresh = await browser.newPage()
  try {
    await fresh.goto(savedUrl)
    await expect(fresh.getByRole('textbox', { name: 'Graph title' })).toHaveValue('Shared example')
    await expect(fresh.getByRole('textbox', { name: 'Weight A to B' })).toHaveValue('2.5')
    await expect(fresh.getByRole('switch', { name: 'Directed graph' })).toBeChecked()
    await fresh.getByRole('button', { name: 'Saved graphs' }).click()
    await expect(fresh.getByRole('link', { name: /Shared example/ }).first()).toBeVisible()
  } finally {
    await fresh.close()
  }
})

test('drags nodes and plays, reverses, and resets both traversals', async ({ page }) => {
  await page.goto('/')
  const node = page.getByRole('button', { name: 'Node C' })
  const before = await node.getAttribute('transform')
  const box = await node.boundingBox()
  if (!box) throw new Error('Node is not on the canvas')
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 40, box.y + box.height / 2 - 25, { steps: 4 })
  await page.mouse.up()
  await expect(node).not.toHaveAttribute('transform', before ?? '')
  await page.getByRole('button', { name: 'Step forward' }).click()
  await expect(page.locator('button[aria-current=step]')).toContainText('Visit node A')
  await page.getByRole('button', { name: 'Step backward' }).click()
  await expect(page.locator('button[aria-current=step]')).toContainText('Add start node A to the queue')
  await page.getByRole('button', { name: 'DFS Depth-first' }).click()
  await expect(page.getByRole('heading', { name: 'Stack', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  await expect(page.locator('button[aria-current=step]')).toContainText('Visit node A')
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  await page.getByRole('slider', { name: 'Playback position' }).press('End')
  await expect(page.locator('button[aria-current=step]')).toContainText('Trace the path')
  await expect(page.locator('.graph-edge.state-path').first()).toBeVisible()
  await page.getByRole('button', { name: 'Reset playback' }).click()
  await expect(page.locator('button[aria-current=step]')).toContainText('Push start node A onto the stack')
})
