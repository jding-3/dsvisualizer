import { expect, test } from '@playwright/test'

test('reverses a weighted edge in the matrix and opens its snapshot in a fresh browser', async ({ page, browser, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await expect(page).toHaveTitle(/GraphLab/)
  await page.getByRole('button', { name: 'Clear graph' }).click()
  const canvas = page.getByRole('group', { name: 'Interactive graph canvas' })
  await canvas.click({ position: { x: 200, y: 140 } })
  await canvas.click({ position: { x: 340, y: 225 } })
  await page.getByRole('switch', { name: 'Directed graph' }).click()
  await page.getByRole('switch', { name: 'Weighted graph' }).click()
  await page.getByRole('button', { name: 'Connect' }).click()
  await canvas.getByRole('button', { name: 'Node A' }).click()
  await canvas.getByRole('button', { name: 'Node B' }).click()
  const weight = page.getByRole('textbox', { name: 'Weight A to B' })
  await weight.fill('2.5')
  await weight.press('Enter')
  const matrix = page.getByRole('region', { name: 'Adjacency matrix' })
  const forward = matrix.getByRole('button', { name: 'A to B', exact: true })
  const reverse = matrix.getByRole('button', { name: 'B to A', exact: true })
  await expect(forward).toHaveText('2.5')
  await forward.click()
  await matrix.getByRole('button', { name: 'Reverse edge' }).click()
  await expect(forward).toHaveAccessibleDescription('No edge')
  await expect(reverse).toHaveText('2.5')
  await expect(reverse).toBeFocused()
  await expect(page.getByRole('textbox', { name: 'Weight B to A' })).toHaveValue('2.5')
  await page.getByRole('slider', { name: 'Playback position' }).press('End')
  await expect(page.locator('button[aria-current=step]')).toContainText('no path from A to B')
  await page.getByRole('textbox', { name: 'Graph title' }).fill('Shared example')
  await page.getByRole('button', { name: 'Save & Share' }).click()
  const link = page.getByRole('textbox', { name: 'Share URL' })
  await expect(link).toHaveValue(/\/graph\/[a-f0-9-]+$/)
  const savedUrl = await link.inputValue()
  const clipboard = await page.evaluate(() => navigator.clipboard.readText())
  expect(clipboard).toBe(savedUrl)
  const fresh = await browser.newPage()
  try {
    await fresh.goto(savedUrl)
    await expect(fresh.getByRole('textbox', { name: 'Graph title' })).toHaveValue('Shared example')
    await expect(fresh.getByRole('textbox', { name: 'Weight B to A' })).toHaveValue('2.5')
    await expect(fresh.getByRole('switch', { name: 'Directed graph' })).toBeChecked()
    await fresh.getByRole('button', { name: 'Saved graphs' }).click()
    await expect(fresh.getByRole('link', { name: /Shared example/ }).first()).toBeVisible()
  } finally {
    await fresh.close()
  }
})

test('adds and removes mirrored and reciprocal edges with the matrix', async ({ page }) => {
  await page.goto('/')
  const matrix = page.getByRole('region', { name: 'Adjacency matrix' })
  const forward = matrix.getByRole('button', { name: 'A to B', exact: true })
  const reverse = matrix.getByRole('button', { name: 'B to A', exact: true })
  await reverse.hover()
  await expect(page.locator('.graph-edge.matrix-highlight')).toHaveCount(1)
  await matrix.getByRole('button', { name: 'A to A', exact: true }).hover()
  await expect(page.locator('.graph-edge.matrix-highlight')).toHaveCount(0)
  await expect(forward).toHaveText('1')
  await expect(reverse).toHaveText('1')
  await forward.click()
  await forward.press('ArrowDown')
  await matrix.getByRole('button', { name: 'B to B', exact: true }).press('ArrowLeft')
  await expect(reverse).toBeFocused()
  await matrix.getByRole('button', { name: 'Remove edge' }).click()
  await expect(forward).toHaveText('0')
  await expect(reverse).toHaveText('0')
  await matrix.getByRole('button', { name: 'Add edge' }).click()
  await expect(forward).toHaveText('1')
  await page.getByRole('switch', { name: 'Directed graph' }).click()
  await expect(reverse).toHaveText('1')
  await forward.click()
  await matrix.getByRole('button', { name: 'Add edge' }).click()
  await expect(matrix.getByRole('button', { name: 'Reverse edge' })).toBeDisabled()
  await matrix.getByRole('button', { name: 'Remove edge' }).click()
  await expect(reverse).toHaveText('1')
})

test('drags nodes and plays, reverses, and resets both traversals', async ({ page }) => {
  await page.goto('/')
  const node = page.getByRole('button', { name: 'Node C' })
  const before = await node.getAttribute('transform')
  const box = await node.boundingBox()
  if (!box) throw new Error('Node is not on the canvas')
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 40, box.y + box.height / 2 - 25, { steps: 4 })
  await page.mouse.up()
  await expect(node).not.toHaveAttribute('transform', before ?? '')
  await page.getByRole('button', { name: 'Step forward' }).click()
  await expect(page.locator('button[aria-current=step]')).toContainText('Visit node A')
  await page.getByRole('button', { name: 'Step backward' }).click()
  await expect(page.locator('button[aria-current=step]')).toContainText('Add start node A to the queue')
  await page.getByRole('button', { name: 'DFS Depth-first' }).click()
  await expect(page.getByRole('heading', { name: 'Stack', exact: true })).toBeVisible()
  await expect(page.getByRole('table', { name: 'Graph connections' })).toBeInViewport()
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  await expect(page.locator('button[aria-current=step]')).toContainText('Visit node A')
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  await page.getByRole('slider', { name: 'Playback position' }).press('End')
  await expect(page.locator('button[aria-current=step]')).toContainText('Trace the path')
  await expect(page.locator('.graph-edge.state-path').first()).toBeVisible()
  await page.getByRole('button', { name: 'Reset playback' }).click()
  await expect(page.locator('button[aria-current=step]')).toContainText('Push start node A onto the stack')
})

for (const [width, height] of [[1280, 720], [320, 568]]) {
  test(`keeps the sample graph, editable matrix, and playback on screen at ${width}×${height}`, async ({ page }) => {
    await page.setViewportSize({ width, height })
    await page.goto('/')
    const graph = page.getByRole('group', { name: 'Interactive graph canvas' })
    const matrix = page.getByRole('table', { name: 'Graph connections' })
    const playback = page.getByRole('button', { name: 'Play', exact: true })
    const timeline = page.getByRole('slider', { name: 'Playback position' })
    const lastCell = matrix.getByRole('button', { name: 'G to G', exact: true })

    for (const name of ['BFS Breadth-first', 'DFS Depth-first']) {
      await page.getByRole('button', { name, exact: true }).click()
      await timeline.press('End')
      await expect(graph).toBeInViewport({ ratio: 1 })
      await expect(lastCell).toBeInViewport({ ratio: 1 })
      await expect(playback).toBeInViewport({ ratio: 1 })
      const graphBounds = (await graph.boundingBox())!
      expect(graphBounds.height).toBeGreaterThanOrEqual(110)
      expect((await matrix.boundingBox())!.y).toBeGreaterThan(graphBounds.y + graphBounds.height)
      expect(await page.evaluate(() => document.documentElement.scrollHeight)).toBeLessThanOrEqual(height)
      expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    }
  })
}
